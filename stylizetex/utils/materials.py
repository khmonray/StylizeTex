"""Safe, marker-based material assignment for generated stylized images.

The process operator must be able to make a generated texture immediately
visible on the active material without destroying the user's shader. This
module implements a single-node, marker-based assignment:

* the original source Image Texture node is kept in the tree untouched;
* exactly one marked Image Texture node holds the generated image and it is
  reused on repeated runs instead of stacking new nodes;
* only the Principled BSDF ``Base Color`` link is redirected;
* all unrelated nodes and links are never modified;
* the generated image carries a marker so an obsolete generated image can be
  removed safely (only when it has no remaining users) while source and foreign
  images are never deleted.

The marker custom properties live on the node and on the image, so the state
survives saving and reloading a ``.blend`` file.
"""

from __future__ import annotations

from .validation import get_principled_bsdf

# Custom-property keys used to identify our generated data-blocks.
GENERATED_NODE_MARKER = "stylizetex_generated_node"
SOURCE_NODE_MARKER = "stylizetex_source_node"
SOURCE_IMAGE_MARKER = "stylizetex_source_image"
GENERATED_IMAGE_MARKER = "stylizetex_generated_image"

GENERATED_NODE_NAME = "StylizeTex_Generated"


def is_generated_node(node) -> bool:
    """Return ``True`` when *node* is our marked generated image node."""

    if node is None:
        return False
    return bool(node.get(GENERATED_NODE_MARKER))


def is_generated_image(image) -> bool:
    """Return ``True`` when *image* is a generated image created by us."""

    if image is None:
        return False
    return bool(image.get(GENERATED_IMAGE_MARKER))


def mark_generated_image(image, source_image) -> None:
    """Record marker metadata on a freshly generated image.

    The markers let the operator recognise its own output later, so it can
    replace it or remove it when unused without ever touching source or foreign
    images.
    """

    if image is None:
        return
    image[GENERATED_IMAGE_MARKER] = True
    image[SOURCE_IMAGE_MARKER] = source_image.name if source_image is not None else ""


def remove_generated_image_if_unused(image) -> bool:
    """Remove a generated image only when it is ours and has no users.

    Source and foreign images are never removed, and a generated image that is
    still referenced somewhere is left alone. Returns ``True`` when the image
    was removed.
    """

    if not is_generated_image(image):
        return False
    if image.users > 0:
        return False

    import bpy

    try:
        bpy.data.images.remove(image)
    except (RuntimeError, ReferenceError):
        return False
    return True


def remove_other_generated_images(source_image, keep_image=None) -> int:
    """Remove orphan generated images recorded for *source_image*.

    The process operator creates a new image data-block for every run. When the
    result is not applied to a material (or when an earlier run left it unused)
    that data-block has no users and would otherwise accumulate. This helper
    removes only images that are all of:

    * marked as generated by us;
    * recorded against *source_image* (when it has a name);
    * not *keep_image*;
    * unused (``users == 0``).

    Source images, foreign images and any in-use generated image are never
    removed. Returns the number of images removed.
    """

    import bpy

    source_name = source_image.name if source_image is not None else ""
    removed = 0
    for image in list(bpy.data.images):
        if image is keep_image or not is_generated_image(image):
            continue
        if source_name and image.get(SOURCE_IMAGE_MARKER) != source_name:
            continue
        if image.users > 0:
            continue
        try:
            bpy.data.images.remove(image)
        except (RuntimeError, ReferenceError):
            continue
        removed += 1
    return removed


def _restore_node_properties(node, previous_properties) -> None:
    """Restore previously snapshotted custom properties on *node*."""

    if node is None or not previous_properties:
        return
    for key, value in previous_properties.items():
        if value is None:
            try:
                del node[key]
            except Exception:
                pass
        else:
            node[key] = value


def find_generated_node(node_tree):
    """Return the first marked generated node of *node_tree*, or ``None``."""

    if node_tree is None:
        return None
    for node in node_tree.nodes:
        if is_generated_node(node):
            return node
    return None


def get_base_color_node(material):
    """Return the node directly linked to Base Color, or ``None``."""

    bsdf = get_principled_bsdf(material)
    if bsdf is None:
        return None
    base_color = bsdf.inputs.get("Base Color")
    if base_color is None or not base_color.is_linked:
        return None
    return base_color.links[0].from_node


def get_source_node(material):
    """Return ``(source_node, source_image)`` unwrapping a generated node.

    When the Base Color link already points at our marked generated node, the
    recorded original source node/image is returned instead. This keeps repeated
    processing reading the true source and never feeds the generated result back
    into the pipeline.
    """

    node = get_base_color_node(material)
    if node is None or node.type != "TEX_IMAGE":
        return None, None

    if not is_generated_node(node):
        return node, node.image

    node_tree = material.node_tree
    source_node_name = node.get(SOURCE_NODE_MARKER)
    if source_node_name and node_tree is not None:
        source_node = node_tree.nodes.get(source_node_name)
        if source_node is not None and source_node.type == "TEX_IMAGE":
            return source_node, source_node.image

    source_image_name = node.get(SOURCE_IMAGE_MARKER)
    if source_image_name:
        import bpy

        source_image = bpy.data.images.get(source_image_name)
        if source_image is not None:
            return None, source_image
    return None, None


def get_source_image(material):
    """Return the effective source image, unwrapping a generated node."""

    return get_source_node(material)[1]


def apply_generated_image(material, generated_image, source_node, source_image):
    """Redirect the material Base Color link to *generated_image*.

    The original source node is kept in the tree; only the Base Color link is
    changed. An existing marked generated node is reused and an obsolete
    generated image is removed when unused. Raises ``RuntimeError`` when the
    material has no usable Principled BSDF Base Color link; on failure the
    Base Color link and the generated node are restored as far as possible.
    """

    node_tree = getattr(material, "node_tree", None)
    if node_tree is None:
        raise RuntimeError("Active material has no node tree.")

    bsdf = get_principled_bsdf(material)
    if bsdf is None:
        raise RuntimeError("Active material has no active Principled BSDF output.")

    base_color = bsdf.inputs.get("Base Color")
    if base_color is None:
        raise RuntimeError("Principled BSDF has no Base Color input.")

    existing_node = find_generated_node(node_tree)
    created_node = existing_node is None
    previous_image = existing_node.image if existing_node is not None else None

    # Snapshot the reused node's custom properties so a failed apply restores
    # them exactly instead of leaving the marker/source metadata pointing at the
    # image that was not applied. A freshly created node has nothing to restore.
    previous_properties = None
    if existing_node is not None:
        previous_properties = {
            GENERATED_NODE_MARKER: existing_node.get(GENERATED_NODE_MARKER),
            SOURCE_NODE_MARKER: existing_node.get(SOURCE_NODE_MARKER),
            SOURCE_IMAGE_MARKER: existing_node.get(SOURCE_IMAGE_MARKER),
            GENERATED_IMAGE_MARKER: existing_node.get(GENERATED_IMAGE_MARKER),
        }

    # Snapshot the current Base Color links so we can restore them on failure.
    previous_links = [
        (link.from_node, link.from_socket, link.to_socket) for link in base_color.links
    ]

    node = existing_node
    try:
        if node is None:
            node = node_tree.nodes.new("ShaderNodeTexImage")
            node.name = GENERATED_NODE_NAME
            node.label = "StylizeTex (generated)"

        node.image = generated_image
        node[GENERATED_NODE_MARKER] = True
        node[SOURCE_NODE_MARKER] = source_node.name if source_node is not None else ""
        node[SOURCE_IMAGE_MARKER] = source_image.name if source_image is not None else ""
        node[GENERATED_IMAGE_MARKER] = generated_image.name

        for link in list(base_color.links):
            node_tree.links.remove(link)
        node_tree.links.new(node.outputs["Color"], base_color)
    except Exception:
        try:
            for link in list(base_color.links):
                node_tree.links.remove(link)
            for _from_node, from_socket, to_socket in previous_links:
                try:
                    node_tree.links.new(from_socket, to_socket)
                except Exception:
                    pass
            if created_node and node is not None:
                node_tree.nodes.remove(node)
            elif node is not None:
                node.image = previous_image
                _restore_node_properties(node, previous_properties)
        finally:
            raise

    # Only now is the previous generated image safely replaceable.
    if previous_image is not None and previous_image is not generated_image:
        remove_generated_image_if_unused(previous_image)

    return node


